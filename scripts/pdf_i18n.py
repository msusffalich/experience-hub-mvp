def normalize_locale(value):
    raw = str(value or "es").strip().lower().replace("_", "-")
    if raw.startswith("en"):
        return "en"
    if raw.startswith("fr"):
        return "fr"
    if raw.startswith("pt"):
        return "pt"
    return "es"


def set_locale(value):
    global _LOCALE
    _LOCALE = normalize_locale(value)
    return _LOCALE


