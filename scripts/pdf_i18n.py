def natural_date(value, include_time=False):
    parsed = _parse_date(value)
    if parsed is None:
        return t("no_data") if not str(value or "").strip() else str(value).strip()
    month = _MONTHS[_LOCALE][parsed.month - 1]
    if _LOCALE == "en":
        rendered = f"{month} {parsed.day}, {parsed.year}"
    elif _LOCALE == "fr":
        day = "1er" if parsed.day == 1 else str(parsed.day)
        rendered = f"{day} {month} {parsed.year}"
    else:
        rendered = f"{parsed.day} de {month} de {parsed.year}"
    if include_time and isinstance(parsed, datetime) and (parsed.hour or parsed.minute):
        rendered += f" · {parsed.hour:02d}:{parsed.minute:02d}"
    return rendered


def _parse_date(value):
    if isinstance(value, datetime):
        return value
    if isinstance(value, date):
        return datetime(value.year, value.month, value.day)
    text = str(value or "").strip()
    if not text:
        return None
    try:
        return datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        match = re.search(r"\b(\d{4})-(\d{2})-(\d{2})\b", text)
        if not match:
            return None
        try:
            return datetime(*(int(part) for part in match.groups()))
        except ValueError:
            return None
